COMMENT ON TABLE payment IS '승인 원장';
COMMENT ON TABLE payment_cancel IS '취소 시도';
COMMENT ON TABLE message_log IS '전문 송수신 로그 (카드번호 마스킹)';
COMMENT ON TABLE acquisition_file IS '매입 내역 파일';
COMMENT ON TABLE acquisition_record IS '매입 내역 레코드';
COMMENT ON TABLE recon_result IS '대사 결과';
COMMENT ON TABLE payout_file IS '지급 파일';
COMMENT ON TABLE settlement IS '가맹점 정산 (가맹점, 매입일, 요율 단위)';
COMMENT ON TABLE settlement_item IS '정산 거래별 금액과 배분 수수료';
