-- V1: 도메인 테이블 12개 (docs/01-erd.md)
--
-- 규칙
-- - 제약 조건에 이름을 붙인다. 이름이 없으면 오류 메시지에 SYS_C008123처럼 나와서 무엇이 막았는지 알 수 없다.
-- - 금액은 NUMBER(15), 요율은 NUMBER(7,6) (ADR-0004). ID는 Java long에 맞춰 NUMBER(19).
-- - 한글이 들어가는 문자열은 VARCHAR2(n CHAR). DB 문자셋(AL32UTF8)에서 한글 1자가 3바이트라서다.
-- - 날짜 의미만 있는 DATE는 시분초가 0이어야 한다 (CHECK col = TRUNC(col)).
-- - 자식 테이블의 FK 컬럼에는 인덱스를 둔다 (docs/04-batch.md 7장). UK·PK의 첫 컬럼이면 그 인덱스로 충분하다.

-- ---------------------------------------------------------------- 가맹점

CREATE TABLE merchant (
                          merchant_id           NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
                          merchant_no           VARCHAR2(10)       NOT NULL,
                          name                  VARCHAR2(40 CHAR)  NOT NULL,
                          settlement_cycle_days NUMBER(2)          NOT NULL,
                          payout_bank_code      CHAR(3)            NOT NULL,
                          payout_account_enc    VARCHAR2(200)      NOT NULL,
                          payout_account_masked VARCHAR2(20)       NOT NULL,
                          holder_name           VARCHAR2(20 CHAR)  NOT NULL,
                          status                VARCHAR2(10)       NOT NULL,
                          api_key_hash          CHAR(64)           NOT NULL,
                          CONSTRAINT pk_merchant PRIMARY KEY (merchant_id),
                          CONSTRAINT uk_merchant_no UNIQUE (merchant_no),
                          CONSTRAINT uk_merchant_api_key UNIQUE (api_key_hash),
                          CONSTRAINT ck_merchant_cycle CHECK (settlement_cycle_days >= 1),
                          CONSTRAINT ck_merchant_status CHECK (status IN ('ACTIVE', 'SUSPENDED'))
);

-- 선분이력. 기간 겹침(I9)은 Oracle에 배제 제약이 없어 코드와 검증 쿼리로 막는다 (ADR-0001).
CREATE TABLE merchant_fee_rate (
                                   merchant_id NUMBER(19)   NOT NULL,
                                   valid_from  DATE         NOT NULL,
                                   valid_to    DATE         NOT NULL,
                                   fee_rate    NUMBER(7, 6) NOT NULL,
                                   CONSTRAINT pk_merchant_fee_rate PRIMARY KEY (merchant_id, valid_from),
                                   CONSTRAINT fk_fee_rate_merchant FOREIGN KEY (merchant_id) REFERENCES merchant (merchant_id),
                                   CONSTRAINT ck_fee_rate_period CHECK (valid_from <= valid_to),
                                   CONSTRAINT ck_fee_rate_from_date CHECK (valid_from = TRUNC(valid_from)),
                                   CONSTRAINT ck_fee_rate_to_date CHECK (valid_to = TRUNC(valid_to)),
                                   CONSTRAINT ck_fee_rate_range CHECK (fee_rate >= 0 AND fee_rate < 1)
);

CREATE TABLE holiday (
                         holiday_date DATE              NOT NULL,
                         name         VARCHAR2(50 CHAR) NOT NULL,
                         CONSTRAINT pk_holiday PRIMARY KEY (holiday_date),
                         CONSTRAINT ck_holiday_date CHECK (holiday_date = TRUNC(holiday_date))
);

-- ---------------------------------------------------------------- 승인·취소

CREATE TABLE payment (
                         payment_id         NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
                         txn_id             VARCHAR2(20)  NOT NULL,
                         merchant_id        NUMBER(19)    NOT NULL,
                         idempotency_key    VARCHAR2(64)  NOT NULL,
                         card_enc           VARCHAR2(200) NOT NULL,
                         card_hash          CHAR(64)      NOT NULL,
                         card_masked        CHAR(16)      NOT NULL,
                         installment_months NUMBER(2)     NOT NULL,
                         amount             NUMBER(15)    NOT NULL,
                         status             VARCHAR2(20)  NOT NULL,
                         result_code        CHAR(4),
                         approval_no        CHAR(8),
                         approved_at        TIMESTAMP,
                         requested_at       TIMESTAMP     NOT NULL,
                         version            NUMBER(10)    DEFAULT 0 NOT NULL,
                         CONSTRAINT pk_payment PRIMARY KEY (payment_id),
                         CONSTRAINT uk_payment_txn_id UNIQUE (txn_id),                                -- I1
                         CONSTRAINT uk_payment_idempotency UNIQUE (merchant_id, idempotency_key),     -- I2, merchant_id FK 인덱스 겸용
                         CONSTRAINT fk_payment_merchant FOREIGN KEY (merchant_id) REFERENCES merchant (merchant_id),
                         CONSTRAINT ck_payment_amount CHECK (amount > 0),
                         CONSTRAINT ck_payment_installment CHECK (installment_months = 0 OR installment_months BETWEEN 2 AND 36),
                         CONSTRAINT ck_payment_status CHECK (status IN ('REQUESTED', 'APPROVED', 'DECLINED', 'UNKNOWN', 'NET_CANCELLED', 'CANCELLED')),
    -- 승인된 적이 있는 결제(APPROVED, CANCELLED)는 승인번호와 승인일시가 있어야 한다
                         CONSTRAINT ck_payment_approval CHECK (
                             status NOT IN ('APPROVED', 'CANCELLED') OR (approval_no IS NOT NULL AND approved_at IS NOT NULL))
);

CREATE INDEX ix_payment_approved_at ON payment (approved_at);                    -- 대사 E01

CREATE TABLE payment_cancel (
                                cancel_id     NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY,
                                payment_id    NUMBER(19)   NOT NULL,
                                cancel_txn_id VARCHAR2(20) NOT NULL,
                                amount        NUMBER(15)   NOT NULL,
                                status        VARCHAR2(20) NOT NULL,
                                result_code   CHAR(4),
                                approval_no   CHAR(8),
                                cancelled_at  TIMESTAMP,
                                CONSTRAINT pk_payment_cancel PRIMARY KEY (cancel_id),
                                CONSTRAINT uk_payment_cancel_txn_id UNIQUE (cancel_txn_id),
                                CONSTRAINT fk_cancel_payment FOREIGN KEY (payment_id) REFERENCES payment (payment_id),
                                CONSTRAINT ck_cancel_amount CHECK (amount > 0),
                                CONSTRAINT ck_cancel_status CHECK (status IN ('REQUESTED', 'CANCELLED', 'FAILED', 'UNKNOWN', 'NET_CANCELLED'))
);

-- 결과를 기다리거나 성공한 취소는 결제당 하나 (docs/01-erd.md). FAILED·NET_CANCELLED는 식이 NULL이라 인덱스에 들어가지 않는다.
CREATE UNIQUE INDEX uk_payment_cancel_active ON payment_cancel (
                                                                CASE WHEN status IN ('REQUESTED', 'UNKNOWN', 'CANCELLED') THEN payment_id END
    );
CREATE INDEX ix_payment_cancel_payment ON payment_cancel (payment_id);           -- FK
CREATE INDEX ix_payment_cancel_cancelled_at ON payment_cancel (cancelled_at);    -- 대사 E02

-- 승인·취소 전문 모두 남기므로 txn_id에 FK를 걸지 않는다. 로그 저장이 FK 때문에 실패하면 안 된다.
CREATE TABLE message_log (
                             log_id         NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
                             txn_id         VARCHAR2(20)       NOT NULL,
                             msg_type       CHAR(4)            NOT NULL,
                             direction      VARCHAR2(4)        NOT NULL,
                             masked_payload VARCHAR2(200 CHAR) NOT NULL,                                  -- 카드번호 마스킹 후 (I10)
                             response_code  CHAR(4),
                             elapsed_ms     NUMBER(10),
                             created_at     TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
                             CONSTRAINT pk_message_log PRIMARY KEY (log_id),
                             CONSTRAINT ck_message_log_direction CHECK (direction IN ('SEND', 'RECV'))
);

CREATE INDEX ix_message_log_txn_id ON message_log (txn_id);

-- ---------------------------------------------------------------- 매입

CREATE TABLE acquisition_file (
                                  file_id           NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
                                  file_name         VARCHAR2(100)      NOT NULL,
                                  card_company_code CHAR(4)            NOT NULL,
                                  business_date     DATE               NOT NULL,
                                  record_count      NUMBER(10),
                                  capture_sum       NUMBER(15),
                                  cancel_sum        NUMBER(15),
                                  status            VARCHAR2(10)       NOT NULL,
                                  reject_reason     VARCHAR2(200 CHAR),
                                  loaded_at         TIMESTAMP,
                                  CONSTRAINT pk_acquisition_file PRIMARY KEY (file_id),
                                  CONSTRAINT uk_acquisition_file_name UNIQUE (file_name),
                                  CONSTRAINT ck_acq_file_status CHECK (status IN ('LOADING', 'LOADED', 'REJECTED')),
                                  CONSTRAINT ck_acq_file_date CHECK (business_date = TRUNC(business_date)),
    -- 거부된 파일은 트레일러를 못 읽었을 수 있어 건수·합계가 없어도 된다. 대신 이유가 있어야 한다.
                                  CONSTRAINT ck_acq_file_totals CHECK (
                                      status = 'REJECTED' OR (record_count IS NOT NULL AND capture_sum IS NOT NULL AND cancel_sum IS NOT NULL)),
                                  CONSTRAINT ck_acq_file_reject_reason CHECK (status <> 'REJECTED' OR reject_reason IS NOT NULL)
);

CREATE TABLE acquisition_record (
                                    record_id     NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY,
                                    file_id       NUMBER(19)   NOT NULL,
                                    record_seq    NUMBER(10)   NOT NULL,
                                    acq_type      CHAR(2)      NOT NULL,
                                    txn_id        VARCHAR2(20) NOT NULL,                                         -- 02도 원거래의 번호
                                    approval_no   CHAR(8)      NOT NULL,
                                    approved_date DATE         NOT NULL,
                                    merchant_no   VARCHAR2(10) NOT NULL,
                                    card_masked   CHAR(16)     NOT NULL,
                                    amount        NUMBER(15)   NOT NULL,                                         -- 02도 양수
                                    CONSTRAINT pk_acquisition_record PRIMARY KEY (record_id),
                                    CONSTRAINT uk_acq_record_seq UNIQUE (file_id, record_seq),                   -- 재시작 중복 방지, file_id FK 인덱스 겸용
                                    CONSTRAINT fk_acq_record_file FOREIGN KEY (file_id) REFERENCES acquisition_file (file_id),
                                    CONSTRAINT ck_acq_record_type CHECK (acq_type IN ('01', '02')),
                                    CONSTRAINT ck_acq_record_amount CHECK (amount > 0),
                                    CONSTRAINT ck_acq_record_date CHECK (approved_date = TRUNC(approved_date))
);

CREATE INDEX ix_acq_record_file_type ON acquisition_record (file_id, acq_type);  -- 대사 A·C

-- ---------------------------------------------------------------- 대사

CREATE TABLE recon_result (
                              recon_id              NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY,
                              business_date         DATE         NOT NULL,
                              acq_type              CHAR(2)      NOT NULL,
                              result_type           VARCHAR2(20) NOT NULL,
                              payment_id            NUMBER(19),
                              acquisition_record_id NUMBER(19),
                              our_amount            NUMBER(15),
                              their_amount          NUMBER(15),
                              resolution            VARCHAR2(10) DEFAULT 'OPEN' NOT NULL,
                              CONSTRAINT pk_recon_result PRIMARY KEY (recon_id),
                              CONSTRAINT uk_recon_record UNIQUE (acquisition_record_id),                   -- I5
                              CONSTRAINT fk_recon_payment FOREIGN KEY (payment_id) REFERENCES payment (payment_id),
                              CONSTRAINT fk_recon_record FOREIGN KEY (acquisition_record_id) REFERENCES acquisition_record (record_id),
                              CONSTRAINT ck_recon_acq_type CHECK (acq_type IN ('01', '02')),
                              CONSTRAINT ck_recon_date CHECK (business_date = TRUNC(business_date)),
                              CONSTRAINT ck_recon_resolution CHECK (resolution IN ('OPEN', 'RESOLVED')),
    -- 유형마다 어느 쪽 기록이 있어야 하는지가 정해져 있다 (docs/04-batch.md 4장)
                              CONSTRAINT ck_recon_shape CHECK (
                                  (result_type = 'UNCAPTURED'   AND payment_id IS NOT NULL AND acquisition_record_id IS NULL)
                                      OR (result_type = 'CAPTURE_ONLY' AND payment_id IS NULL     AND acquisition_record_id IS NOT NULL)
                                      OR (result_type IN ('MATCHED', 'AMOUNT_MISMATCH', 'STATUS_MISMATCH')
                                      AND payment_id IS NOT NULL AND acquisition_record_id IS NOT NULL))
);

CREATE INDEX ix_recon_date_type ON recon_result (business_date, result_type);
CREATE INDEX ix_recon_payment ON recon_result (payment_id);                      -- FK

-- ---------------------------------------------------------------- 정산·지급

CREATE TABLE payout_file (
                             file_id      NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
                             payout_date  DATE          NOT NULL,
                             file_name    VARCHAR2(100) NOT NULL,
                             record_count NUMBER(10)    NOT NULL,
                             total_amount NUMBER(15)    NOT NULL,
                             created_at   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
                             CONSTRAINT pk_payout_file PRIMARY KEY (file_id),
                             CONSTRAINT uk_payout_file_date UNIQUE (payout_date),
                             CONSTRAINT ck_payout_file_date CHECK (payout_date = TRUNC(payout_date))
);

CREATE TABLE settlement (
                            settlement_id  NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY,
                            merchant_id    NUMBER(19)   NOT NULL,
                            business_date  DATE         NOT NULL,
                            payout_date    DATE         NOT NULL,
                            fee_rate       NUMBER(7, 6) NOT NULL,
                            txn_count      NUMBER(10)   NOT NULL,
                            gross_amount   NUMBER(15)   NOT NULL,
                            cancel_amount  NUMBER(15)   NOT NULL,
                            fee_amount     NUMBER(15)   NOT NULL,
                            vat_amount     NUMBER(15)   NOT NULL,
                            net_amount     NUMBER(15)   NOT NULL,
                            payout_file_id NUMBER(19),
                            CONSTRAINT pk_settlement PRIMARY KEY (settlement_id),
                            CONSTRAINT uk_settlement UNIQUE (merchant_id, business_date, fee_rate),      -- merchant_id FK 인덱스 겸용
                            CONSTRAINT fk_settlement_merchant FOREIGN KEY (merchant_id) REFERENCES merchant (merchant_id),
                            CONSTRAINT fk_settlement_payout FOREIGN KEY (payout_file_id) REFERENCES payout_file (file_id),
                            CONSTRAINT ck_settlement_net CHECK (
                                net_amount = gross_amount - cancel_amount - fee_amount - vat_amount),    -- I6
                            CONSTRAINT ck_settlement_dates CHECK (
                                business_date = TRUNC(business_date) AND payout_date = TRUNC(payout_date) AND payout_date > business_date)
);

CREATE INDEX ix_settlement_business_date ON settlement (business_date);
CREATE INDEX ix_settlement_payout_date ON settlement (payout_date);
CREATE INDEX ix_settlement_payout_file ON settlement (payout_file_id);           -- FK

CREATE TABLE settlement_item (
                                 acquisition_record_id NUMBER(19) NOT NULL,
                                 settlement_id         NUMBER(19) NOT NULL,
                                 amount                NUMBER(15) NOT NULL,                                   -- 매입취소는 음수
                                 allocated_fee         NUMBER(15) NOT NULL,
                                 CONSTRAINT pk_settlement_item PRIMARY KEY (acquisition_record_id),           -- 매입 레코드 하나는 한 번만 정산
                                 CONSTRAINT fk_item_record FOREIGN KEY (acquisition_record_id) REFERENCES acquisition_record (record_id),
                                 CONSTRAINT fk_item_settlement FOREIGN KEY (settlement_id) REFERENCES settlement (settlement_id)
);

CREATE INDEX ix_settlement_item_settlement ON settlement_item (settlement_id);   -- FK, 배분 검증

